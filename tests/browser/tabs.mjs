// Tabs: opening several, Ctrl+Tab, Ctrl+1..9, arrows, closing, the wheel on
// the strip, and the session coming back after a restart.
import { start } from './harness.mjs';

const files = Object.fromEntries(['a', 'b', 'c', 'd'].map((n) => [`/d/${n}.md`, `File ${n} text.\n\nMore of ${n}.\n`]));
const { page, ok, finish } = await start({ files });
const names = () => page.$$eval('#tabs .tab', (t) => t.map((x) => x.textContent));
const current = () => page.$eval('#tabs .tab[aria-selected="true"]', (t) => t.textContent).catch(() => null);
const shown = () => page.$eval('#markdown p', (p) => p.textContent.trim());
const settle = () => page.waitForTimeout(250);
const both = async (name) => await current() === name && (await shown()).startsWith(`File ${name[0]} `);

ok((await names()).length === 0, 'One file shows no tab strip');
await page.evaluate(() => window.__emit('open-files', ['/d/b.md', '/d/c.md', '/d/d.md']));
await page.waitForTimeout(500);
ok((await names()).join() === 'a.md,b.md,c.md,d.md', `Files handed over open as tabs (${await names()})`);
ok(await both('b.md'), 'The first file handed over is the one shown');
ok(await page.evaluate(() => window.__calls.filter((c) => c[0] === 'read_markdown').map((c) => c[1].path).join()) === '/d/a.md,/d/b.md', 'Background tabs are not read until shown');
await page.keyboard.press('Control+Tab');
await settle();
ok(await both('c.md'), 'Ctrl+Tab goes to the next tab');
await page.keyboard.press('Control+Shift+Tab');
await page.keyboard.press('Control+Shift+Tab');
await settle();
ok(await both('a.md'), 'Ctrl+Shift+Tab goes back');
await page.keyboard.press('Control+Shift+Tab');
await settle();
ok(await both('d.md'), 'and wraps from the first to the last');
await page.keyboard.press('Control+2');
await settle();
ok(await both('b.md'), 'Ctrl+2 shows the second tab');
await page.keyboard.press('Control+9');
await settle();
ok(await both('b.md'), 'Ctrl+9 past the last tab changes nothing');
await page.click('#markdown', { position: { x: 5, y: 5 } });
await page.keyboard.press('ArrowRight');
await settle();
ok(await both('c.md'), 'Right arrow steps through tabs');
await page.keyboard.press('ArrowLeft');
await settle();
ok(await both('b.md'), 'Left arrow steps back');

await page.hover('#tabs .tab >> nth=0');
await page.mouse.wheel(0, 100);
await settle();
ok(await both('c.md'), 'Wheel down on the strip goes to the next tab');
await page.mouse.wheel(0, -100);
await settle();
ok(await both('b.md'), 'Wheel up goes back');
await page.mouse.wheel(0, 20);
await settle();
ok(await both('b.md'), 'A small trackpad delta does not step alone');
await page.mouse.wheel(0, 40);
await settle();
ok(await both('c.md'), 'Deltas add up to one step');

await page.evaluate(() => { document.getElementById('markdownStage').scrollTop = 0; });
await page.keyboard.press('Control+w');
await settle();
ok((await names()).join() === 'a.md,b.md,d.md', 'Ctrl+W closes the shown tab');
ok(await both('d.md') || await both('b.md'), `A neighbour is shown after a close (${await current()})`);
await page.click('#tabs .tab:has-text("a.md") .shut');
await settle();
ok((await names()).join() === 'b.md,d.md', 'The close mark closes its own tab');
await page.click('#tabs .tab:has-text("b.md")', { button: 'middle' });
await settle();
ok((await names()).length === 0 && await shown() === 'File d text.', 'A middle click closes; one file left drops the strip');
ok(await page.evaluate(() => document.title.startsWith('d.md')), 'The title follows the shown file');

await page.evaluate(() => window.__emit('open-files', ['/d/a.md', '/d/c.md']));
await page.waitForTimeout(500);
await page.keyboard.press('Control+1');
await settle();
await page.evaluate(() => window.__emit('open-files', ['/d/d.md']));
await settle();
ok((await names()).join() === 'd.md,a.md,c.md' && await both('d.md'), 'Opening a file that is open goes to its tab, not a second one');
await page.keyboard.press('Control+3');
await settle();
const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('pdf-next.session')));
ok(saved?.tabs?.map((t) => t.name).join() === 'd.md,a.md,c.md' && saved.active === 2, 'The tabs and the shown one are saved');
await page.evaluate(() => sessionStorage.setItem('noInitial', '1'));
await page.reload();
await page.waitForSelector('#markdown p');
await page.waitForTimeout(500);
ok((await names()).join() === 'd.md,a.md,c.md', `A restart brings the tabs back (${await names()})`);
ok(await both('c.md'), 'with the same tab shown');
await page.evaluate(() => sessionStorage.setItem('fail', JSON.stringify({ open_path: 'gone' })));
await page.reload();
await page.waitForTimeout(800);
ok((await names()).length === 0 && await page.$eval('#empty', (e) => getComputedStyle(e).display !== 'none'), 'Files that are gone are dropped; with none left the window is empty');
await finish();
