// Panes: split, live pane and copies, moving between them, session restore, drag.
import { start } from './harness.mjs';

const { page, ok, selectText, shot, finish } = await start();
const livePath = () => page.evaluate(() => document.getElementById('stage').closest('.pane-body')?.dataset.path);
const copy = (path) => page.evaluate((path) => document.querySelector(`.pane-body[data-path="${path}"] .pane-snapshot`)?.textContent || '', path);
const groups = () => page.$$eval('#panes .dv-groupview', (g) => g.length);
const tabs = () => page.$$eval('#tabs .tab', (t) => t.length);
const pick = (path) => page.evaluate((path) => { window.__pick = path; }, path);
const drag = async (from, to) => {
  await page.mouse.move(from.x + 15, from.y + 10);
  await page.mouse.down();
  await page.mouse.move(from.x + 40, from.y + 30, { steps: 5 });
  await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 20 });
  await page.waitForTimeout(100);
  await page.mouse.up();
  await page.waitForTimeout(500);
};

await pick('/d/b.md');
await page.keyboard.press('Control+Shift+D');
await page.waitForTimeout(500);
ok(await page.$eval('#panes', (p) => !p.hidden), 'Ctrl+Shift+D opens panes');
ok(await groups() === 2, 'Two groups side by side');
const live = await livePath();
ok(live === '/d/b.md', `The new pane is live (${live})`);
ok((await page.textContent('#stage #markdown')).includes('Other file text'), 'Live pane shows b.md');
ok((await copy('/d/a.md')).includes('Hello'), 'The other pane keeps a copy of a.md');
const boxes = await page.$$eval('#panes .dv-groupview', (g) => g.map((x) => { const r = x.getBoundingClientRect(); return [Math.round(r.left), Math.round(r.width)]; }));
ok(boxes[0][0] < boxes[1][0] && boxes[0][1] > 200 && boxes[1][1] > 200, `Groups sit left and right ${JSON.stringify(boxes)}`);
ok(await page.$eval('#splitView', (s) => s.value) === 'right', 'The pane menu says split right');
await shot('panes-right');
await page.click('.pane-body[data-path="/d/a.md"] .pane-cover');
await page.waitForTimeout(400);
ok(await livePath() === '/d/a.md', 'Clicking a pane makes it live');
ok((await copy('/d/b.md')).includes('Other file text'), 'b.md keeps a copy');
await selectText('#markdown', 'world');
await page.keyboard.press('Control+u');
await page.waitForTimeout(300);
ok(await page.evaluate(() => window.__files['/d/a.md'].includes('<u>world</u>')), 'Underline works in a live pane');
await page.keyboard.press('Control+Alt+ArrowRight');
await page.waitForTimeout(400);
ok(await livePath() === '/d/b.md', 'Ctrl+Alt+Right moves to the right pane');
await page.evaluate(() => { window.__files['/d/a.md'] = 'Changed by the agent.\n'; });
await page.evaluate(() => window.__emit?.('file-changed', { path: '/d/a.md', kind: 'changed', revision: 99 }));
await page.waitForTimeout(300);
ok((await copy('/d/a.md')).includes('Changed by the agent'), 'A copy follows its file when it changes');
ok((await page.evaluate(() => window.__calls.filter((c) => c[0] === 'watch_secondary').at(-1)?.[1]?.paths || [])).join() === '/d/a.md', 'The other pane is watched');
await page.selectOption('#mdSize', '22');
await page.waitForTimeout(100);
ok(await page.evaluate(() => document.querySelector('.pane-snapshot article#markdown')?.dataset.size) === '22', 'Text size reaches the copies');
await page.selectOption('#splitView', 'off');
await page.waitForTimeout(400);
ok(await page.$eval('#panes', (p) => p.hidden), 'One pane again');
ok(await page.evaluate(() => document.getElementById('stage').parentElement === document.body), 'Stage is back in the window');
ok(await tabs() === 2, 'Both files are still tabs');
await page.keyboard.press('Control+Shift+E');
await page.waitForTimeout(500);
const rows = await page.$$eval('#panes .dv-groupview', (g) => g.map((x) => Math.round(x.getBoundingClientRect().top)));
ok(rows.length === 2 && rows[0] < rows[1], `Ctrl+Shift+E splits top and bottom ${JSON.stringify(rows)}`);
await shot('panes-down');
const saved = await page.evaluate(() => JSON.parse(localStorage.getItem(Object.keys(localStorage).find((k) => k.includes('session')) || 'null')));
ok(Boolean(saved?.panes?.grid), 'The layout is saved with the session');
await page.evaluate(() => sessionStorage.setItem('noInitial', '1'));
await page.reload();
await page.waitForTimeout(800);
ok(await page.$eval('#panes', (p) => !p.hidden) && await groups() === 2, 'A restart brings the panes back');
const restored = await page.evaluate(() => [...document.querySelectorAll('.pane-body')].map((b) => [b.dataset.path, Boolean(b.querySelector('#stage')), (b.querySelector('.pane-snapshot')?.textContent || '').trim().slice(0, 20)]));
ok(restored.filter((r) => r[1]).length === 1 && restored.some((r) => !r[1] && r[2].length > 0), `One live pane, the other filled ${JSON.stringify(restored)}`);
ok((await page.$$('#panes .dv-tab')).length === 2, 'Each restored pane has one tab');
await drag(await page.locator('#panes .dv-tab').nth(1).boundingBox(), await page.locator('#panes .dv-tabs-and-actions-container').first().boundingBox());
ok(await page.$eval('#panes', (p) => p.hidden), 'Dragging the last tab of a pane onto the other merges back to one pane');
ok(await tabs() === 2, 'Both files stay open after the merge');
await pick('/d/b.md');
await page.keyboard.press('Control+Shift+D');
await page.waitForTimeout(500);
await page.click('#panes .dv-groupview.dv-active-group .dv-tab.dv-active-tab .dv-default-tab-action').catch(() => {});
await page.waitForTimeout(400);
ok(await page.$eval('#panes', (p) => p.hidden) && await tabs() <= 1, 'Closing a tab that empties a pane leaves one pane');
await pick('/d/b.md');
await page.keyboard.press('Control+Shift+D');
await page.waitForTimeout(500);
await pick('/d/c.md');
await page.keyboard.press('Control+Shift+E');
await page.waitForTimeout(500);
ok(await groups() === 3, 'A third pane splits off the live one');
ok((await page.textContent('#stage #markdown')).includes('Third file'), 'The third pane is live with c.md');
await drag(await page.locator('#panes .dv-groupview.dv-active-group .dv-tab').first().boundingBox(), await page.locator('#panes .dv-groupview').first().boundingBox());
ok(await groups() === 2, 'Dropping a tab in the middle of another pane moves it there');
await shot('panes-moved');
await page.selectOption('#splitView', 'off');
await page.waitForTimeout(400);
await pick('/d/hello.pdf');
await page.click('#open');
await page.waitForTimeout(1500);
const pdfShown = () => page.evaluate(() => document.body.classList.contains('kind-pdf') && document.querySelectorAll('#stage .page canvas').length > 0);
ok(await pdfShown(), 'A PDF opens');
await page.keyboard.press('Control+Shift+D');
await page.waitForTimeout(800);
const ink = await page.evaluate(() => {
  const canvas = document.querySelector('.pane-snapshot-pdf canvas');
  if (!canvas) return -1;
  const data = canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data;
  let dark = 0;
  for (let i = 0; i < data.length; i += 4) if (data[i] < 200) dark += 1;
  return dark;
});
ok(ink > 50, `The PDF copy keeps its pixels (${ink} dark)`);
await page.click('.pane-snapshot-pdf .pane-cover');
await page.waitForTimeout(1200);
ok(await pdfShown(), 'Clicking the PDF copy makes the PDF live again');
await shot('panes-pdf');
await finish();
